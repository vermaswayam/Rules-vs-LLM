def pct(value):
    return "N/A" if value is None else f"{value*100:.2f}%"


def number(value, digits=3):
    return "N/A" if value is None else f"{value:,.{digits}f}"


def save(name, lines):
    (ROOT / name).write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


